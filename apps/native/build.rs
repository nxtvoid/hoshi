//! Turns `messages/*.json` into one function per message in `m`, which picks the text of the
//! locale shown. Parameters go in alphabetical order; a plural's count is a `usize`, every other
//! parameter anything `Display`. Every locale has the same messages with the same parameters.

use serde_json::{Map, Value};
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::PathBuf;

/// Each locale's file and its variant of `Locale`; the first one's messages are the reference.
const LOCALES: [(&str, &str); 2] = [
    ("messages/en.json", "English"),
    ("messages/es.json", "Spanish"),
];
const ICON: &str = "icons/icon.ico";
const DEV_ICON: &str = "icons/dev/icon.ico";

fn main() {
    let locales = LOCALES.map(|(file, variant)| {
        println!("cargo:rerun-if-changed={file}");
        let text =
            std::fs::read_to_string(file).unwrap_or_else(|error| panic!("read {file}: {error}"));
        let messages: Map<String, Value> =
            serde_json::from_str(&text).unwrap_or_else(|error| panic!("parse {file}: {error}"));
        (file, variant, messages)
    });
    let (reference_file, _, reference) = &locales[0];
    for (file, _, messages) in &locales[1..] {
        if let Some(key) = messages.keys().find(|key| !reference.contains_key(*key)) {
            panic!("{file}: {key} is not in {reference_file}");
        }
    }

    let mut out = String::from("// Generated by build.rs from apps/native/messages.\n");
    for key in reference.keys().filter(|key| !key.starts_with('$')) {
        let texts = locales.each_ref().map(|(file, variant, messages)| {
            let value = messages
                .get(key)
                .unwrap_or_else(|| panic!("{file}: {key} is missing"));
            (*variant, Text::read(file, key, value))
        });
        let shape = texts[0].1.shape();
        for ((file, _, _), (_, text)) in locales.iter().zip(&texts) {
            if text.shape() != shape {
                panic!("{file}: {key} doesn't have the parameters it has in {reference_file}");
            }
        }
        function(&mut out, key, &shape, &texts);
    }
    let path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("messages.rs");
    std::fs::write(path, out).expect("write messages.rs");

    windows_icon();
}

/// GPUI takes the window and taskbar icon from the executable's icon resource with id 1.
fn windows_icon() {
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }
    let icon = if std::env::var_os("CARGO_CFG_DEBUG_ASSERTIONS").is_some() {
        DEV_ICON
    } else {
        ICON
    };
    println!("cargo:rerun-if-changed={icon}");
    tauri_winres::WindowsResource::new()
        .set_icon_with_id(icon, "1")
        .set("ProductName", "hoshi")
        .set("FileDescription", "hoshi")
        .compile()
        .expect("embed the Windows icon");
}

/// A message's parameters, and which of them is the plural's count.
type Shape = (BTreeSet<String>, Option<String>);

enum Text {
    Simple(String),
    Plural {
        count: String,
        one: String,
        other: String,
    },
}

impl Text {
    fn read(file: &str, key: &str, value: &Value) -> Self {
        match value {
            Value::String(text) => Self::Simple(text.clone()),
            Value::Array(variants) => Self::plural(file, key, &variants[0]),
            _ => panic!("{file}: {key}: unexpected shape"),
        }
    }

    fn plural(file: &str, key: &str, variant: &Value) -> Self {
        let declarations = variant["declarations"].as_array().expect("declarations");
        let count = declarations[0]
            .as_str()
            .and_then(|line| line.strip_prefix("input "))
            .expect("plural input");
        let matches = variant["match"].as_object().expect("match");
        let (mut one, mut other) = (None, None);
        for (selector, text) in matches {
            let text = text.as_str().expect("plural text").to_owned();
            match selector.rsplit('=').next() {
                Some("one") => one = Some(text),
                Some("*") => other = Some(text),
                _ => panic!("{file}: {key}: unexpected selector {selector}"),
            }
        }
        Self::Plural {
            count: count.to_owned(),
            one: one.expect("one"),
            other: other.expect("other"),
        }
    }

    fn shape(&self) -> Shape {
        match self {
            Self::Simple(text) => (params(&[text]), None),
            Self::Plural { count, one, other } => (params(&[one, other]), Some(count.clone())),
        }
    }

    fn body(&self) -> String {
        match self {
            Self::Simple(text) => format_call(text),
            Self::Plural { count, one, other } => format!(
                "if {} == 1 {{ {} }} else {{ {} }}",
                ident(count),
                format_call(one),
                format_call(other)
            ),
        }
    }
}

fn function(out: &mut String, key: &str, (params, count): &Shape, texts: &[(&str, Text)]) {
    let args: Vec<String> = params
        .iter()
        .map(|param| {
            if count.as_ref() == Some(param) {
                format!("{}: usize", ident(param))
            } else {
                format!("{}: impl std::fmt::Display", ident(param))
            }
        })
        .collect();
    writeln!(
        out,
        "pub fn {}({}) -> String {{\n    match crate::locale::current() {{",
        ident(key),
        args.join(", ")
    )
    .unwrap();
    for (variant, text) in texts {
        writeln!(
            out,
            "        crate::locale::Locale::{variant} => {{ {} }}",
            text.body()
        )
        .unwrap();
    }
    out.push_str("    }\n}\n");
}

fn params(texts: &[&str]) -> BTreeSet<String> {
    let mut found = BTreeSet::new();
    for text in texts {
        let mut rest = *text;
        while let Some(start) = rest.find('{') {
            let end = rest[start..].find('}').expect("closing brace") + start;
            found.insert(rest[start + 1..end].to_owned());
            rest = &rest[end + 1..];
        }
    }
    found
}

/// `format!` with the message's `{name}` placeholders bound to the parameters.
fn format_call(text: &str) -> String {
    let mut template = String::new();
    let mut rest = text;
    while let Some(start) = rest.find('{') {
        let end = rest[start..].find('}').expect("closing brace") + start;
        template.push_str(&rest[..start].replace('}', "}}"));
        write!(template, "{{{}}}", ident(&rest[start + 1..end])).unwrap();
        rest = &rest[end + 1..];
    }
    template.push_str(&rest.replace('}', "}}"));
    let bindings: Vec<String> = params(&[text])
        .iter()
        .map(|param| format!("{0} = {0}", ident(param)))
        .collect();
    if bindings.is_empty() {
        format!("{text:?}.to_owned()")
    } else {
        format!("format!({template:?}, {})", bindings.join(", "))
    }
}

/// A message key or parameter as a Rust identifier: camelCase to snake_case.
fn ident(name: &str) -> String {
    let mut snake = String::new();
    for ch in name.chars() {
        if ch.is_ascii_uppercase() {
            snake.push('_');
            snake.push(ch.to_ascii_lowercase());
        } else {
            snake.push(ch);
        }
    }
    match snake.as_str() {
        "type" | "move" | "ref" | "self" | "match" | "use" | "mod" | "fn" | "loop" | "box"
        | "where" | "async" | "await" | "dyn" | "impl" | "in" | "as" | "static" | "struct" => {
            format!("r#{snake}")
        }
        _ => snake,
    }
}
