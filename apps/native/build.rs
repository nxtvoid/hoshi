//! Turns `messages/en.json` into one function per message in `m`. Parameters go in alphabetical
//! order; a plural's count is a `usize`, every other parameter anything `Display`.

use serde_json::{Map, Value};
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::PathBuf;

const MESSAGES: &str = "messages/en.json";
const ICON: &str = "icons/icon.ico";
const DEV_ICON: &str = "icons/dev/icon.ico";

fn main() {
    println!("cargo:rerun-if-changed={MESSAGES}");
    let text = std::fs::read_to_string(MESSAGES).expect("read messages/en.json");
    let messages: Map<String, Value> = serde_json::from_str(&text).expect("parse messages/en.json");

    let mut out = String::from("// Generated by build.rs from apps/native/messages/en.json.\n");
    for (key, value) in &messages {
        if key.starts_with('$') {
            continue;
        }
        match value {
            Value::String(text) => simple(&mut out, key, text),
            Value::Array(variants) => plural(&mut out, key, &variants[0]),
            _ => panic!("message {key}: unexpected shape"),
        }
    }
    let path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("messages.rs");
    std::fs::write(path, out).expect("write messages.rs");

    windows_icon();
}

/// GPUI takes the window and taskbar icon from the executable's icon resource with id 1.
fn windows_icon() {
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }
    let icon = if std::env::var_os("CARGO_CFG_DEBUG_ASSERTIONS").is_some() {
        DEV_ICON
    } else {
        ICON
    };
    println!("cargo:rerun-if-changed={icon}");
    tauri_winres::WindowsResource::new()
        .set_icon_with_id(icon, "1")
        .set("ProductName", "hoshi")
        .set("FileDescription", "hoshi")
        .compile()
        .expect("embed the Windows icon");
}

fn simple(out: &mut String, key: &str, text: &str) {
    let params = params(&[text]);
    let args: Vec<String> = params
        .iter()
        .map(|param| format!("{}: impl std::fmt::Display", ident(param)))
        .collect();
    writeln!(
        out,
        "pub fn {}({}) -> String {{",
        ident(key),
        args.join(", ")
    )
    .unwrap();
    writeln!(out, "    {}", format_call(text, &params)).unwrap();
    out.push_str("}\n");
}

fn plural(out: &mut String, key: &str, variant: &Value) {
    let declarations = variant["declarations"].as_array().expect("declarations");
    let input = declarations[0]
        .as_str()
        .and_then(|line| line.strip_prefix("input "))
        .expect("plural input");
    let matches = variant["match"].as_object().expect("match");
    let (mut one, mut other) = (None, None);
    for (selector, text) in matches {
        let text = text.as_str().expect("plural text");
        match selector.rsplit('=').next() {
            Some("one") => one = Some(text),
            Some("*") => other = Some(text),
            _ => panic!("message {key}: unexpected selector {selector}"),
        }
    }
    let (one, other) = (one.expect("one"), other.expect("other"));
    let params = params(&[one, other]);
    let args: Vec<String> = params
        .iter()
        .map(|param| {
            if param == input {
                format!("{}: usize", ident(param))
            } else {
                format!("{}: impl std::fmt::Display", ident(param))
            }
        })
        .collect();
    writeln!(
        out,
        "pub fn {}({}) -> String {{",
        ident(key),
        args.join(", ")
    )
    .unwrap();
    writeln!(
        out,
        "    if {} == 1 {{ {} }} else {{ {} }}",
        ident(input),
        format_call(one, &params),
        format_call(other, &params)
    )
    .unwrap();
    out.push_str("}\n");
}

fn params(texts: &[&str]) -> BTreeSet<String> {
    let mut found = BTreeSet::new();
    for text in texts {
        let mut rest = *text;
        while let Some(start) = rest.find('{') {
            let end = rest[start..].find('}').expect("closing brace") + start;
            found.insert(rest[start + 1..end].to_owned());
            rest = &rest[end + 1..];
        }
    }
    found
}

/// `format!` with the message's `{name}` placeholders bound to the parameters.
fn format_call(text: &str, params: &BTreeSet<String>) -> String {
    let mut template = String::new();
    let mut rest = text;
    while let Some(start) = rest.find('{') {
        let end = rest[start..].find('}').expect("closing brace") + start;
        template.push_str(&rest[..start].replace('}', "}}"));
        write!(template, "{{{}}}", ident(&rest[start + 1..end])).unwrap();
        rest = &rest[end + 1..];
    }
    template.push_str(&rest.replace('}', "}}"));
    let bindings: Vec<String> = params
        .iter()
        .map(|param| format!("{0} = {0}", ident(param)))
        .collect();
    if bindings.is_empty() {
        format!("{text:?}.to_owned()")
    } else {
        format!("format!({template:?}, {})", bindings.join(", "))
    }
}

/// A message key or parameter as a Rust identifier: camelCase to snake_case.
fn ident(name: &str) -> String {
    let mut snake = String::new();
    for ch in name.chars() {
        if ch.is_ascii_uppercase() {
            snake.push('_');
            snake.push(ch.to_ascii_lowercase());
        } else {
            snake.push(ch);
        }
    }
    match snake.as_str() {
        "type" | "move" | "ref" | "self" | "match" | "use" | "mod" | "fn" | "loop" | "box"
        | "where" | "async" | "await" | "dyn" | "impl" | "in" | "as" | "static" | "struct" => {
            format!("r#{snake}")
        }
        _ => snake,
    }
}
